pub fn draw_glyph_rgba8888(
    frame: &mut [u8],
    stride_pixels: usize,
    x: i32,
    y: i32,
    color_rgb: u32,
    ch: u8,
) {
    let rows = bitmap_glyph_rows(ch);
    for (row_index, bits) in rows.iter().copied().enumerate() {
        for column in 0..BITMAP_GLYPH_WIDTH {
            if (bits >> (BITMAP_GLYPH_WIDTH - 1 - column)) & 1 == 0 {
                continue;
            }
            let px = x + column as i32;
            let py = y + row_index as i32;
            if px < 0 || py < 0 {
                continue;
            }
            set_pixel_rgba8888(frame, stride_pixels, px as usize, py as usize, color_rgb);
        }
    }
}

pub fn draw_text_rgba8888(
    frame: &mut [u8],
    stride_pixels: usize,
    x: i32,
    y: i32,
    color_rgb: u32,
    text: &str,
) {
    for (index, byte) in text.as_bytes().iter().copied().enumerate() {
        draw_glyph_rgba8888(
            frame,
            stride_pixels,
            x + (index as i32 * BITMAP_GLYPH_ADVANCE as i32),
            y,
            color_rgb,
            normalize_bitmap_glyph(byte),
        );
    }
}

pub fn set_pixel_rgba8888(
    frame: &mut [u8],
    stride_pixels: usize,
    x: usize,
    y: usize,
    color_rgb: u32,
) {
    let index = ((y * stride_pixels) + x) * 4;
    if index + 4 > frame.len() {
        return;
    }
    frame[index..index + 4].copy_from_slice(&(color_rgb & 0x00ff_ffff).to_le_bytes());
}
